export function helpHTML() {
  const cur = HELP_TABS.find(t => t[0] === UIS.helpTab) || HELP_TABS[0];
  return head('가이드', 'gear', '<button class="btn ghost" data-a="helpBack" type="button" style="min-height:36px;padding:0 10px;font-size:16px">설정</button>')
    + `<div class="sh-body"><div class="tabs" style="flex-wrap:wrap;overflow:visible">${HELP_TABS.map(([k, n]) => `<button type="button" class="tab ${k === cur[0] ? 'on' : ''}" data-a="helpTab" data-i="${k}">${n}</button>`).join('')}</div>`
    + `<div class="keys">${cur[2]().map(([b, s]) => `<b>${b}</b><span>${s}</span>`).join('')}</div></div>`;
}
